// 分类索引（全部 → 不筛）
const CATEGORY_LABELS = Object.fromEntries(
  INJURY_CATEGORIES.map((c) => [c.key, c.label]),
)

// 文章列表（附分类中文标签）：category 缺省返回全部
export async function getArticles(category, token) {
  verifyAccess(token)
  await sleep(260)
  const list = (category ? ARTICLES.filter((a) => a.category === category) : ARTICLES).map(
    (a) => ({
      ...a,
      categoryLabel: CATEGORY_LABELS[a.category],
    }),
  )
  return JSON.parse(JSON.stringify(list))
}

// 文章详情：含完整分节
export async function getArticleDetail(id, token) {
  verifyAccess(token)
  await sleep(200)
  const article = ARTICLES.find((a) => a.id === id)
  if (!article) {
    const err = new Error('文章不存在')
    err.response = { status: 404, data: { message: '文章不存在' } }
    throw err
  }
  return JSON.parse(JSON.stringify({ ...article, categoryLabel: CATEGORY_LABELS[article.category] }))
}

// 分类列表（视图渲染 chips 用）
export async function getCategories(token) {
  verifyAccess(token)
  await sleep(100)
  return INJURY_CATEGORIES.map((c) => ({ ...c }))
}